const ALPHABIT: number = 0;
const DIGITBIT: number = 1;
const PRINTBIT: number = 2;
const SPACEBIT: number = 3;
const XDIGITBIT: number = 4;

const lisdigit = function (c: number): boolean {
    const value = luai_ctype_[c + 1] ?? 0;
    return (value & (1 << DIGITBIT)) !== 0;
};

const lisxdigit = function (c: number): boolean {
    const value = luai_ctype_[c + 1] ?? 0;
    return (value & (1 << XDIGITBIT)) !== 0;
};

const lisprint = function (c: number): boolean {
    const value = luai_ctype_[c + 1] ?? 0;
    return (value & (1 << PRINTBIT)) !== 0;
};

const lisspace = function (c: number): boolean {
    const value = luai_ctype_[c + 1] ?? 0;
    return (value & (1 << SPACEBIT)) !== 0;
};

const lislalpha = function (c: number): boolean {
    const value = luai_ctype_[c + 1] ?? 0;
    return (value & (1 << ALPHABIT)) !== 0;
};

const lislalnum = function (c: number): boolean {
    const value = luai_ctype_[c + 1] ?? 0;
    return (value & ((1 << ALPHABIT) | (1 << DIGITBIT))) !== 0;
};

export { lisdigit, lislalnum, lislalpha, lisprint, lisspace, lisxdigit };
